#!/usr/bin/env bash
set -Eeuo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."
if [[ ${1:-} != --remove-launchers ]]; then
    echo "Usage: $0 --remove-launchers (keeps the checkout, models and all BudAI data)" >&2
    exit 2
fi
bud_unit="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/budai.service"
bud_entry="${XDG_DATA_HOME:-$HOME/.local/share}/applications/budai.desktop"
if [[ -f "$bud_unit" && ! -L "$bud_unit" ]] && grep -q -F -- '# Generated by BudAI' "$bud_unit" && grep -q -F -- "$PWD/scripts/budai" "$bud_unit"; then
    if systemctl --user is-enabled budai.service >/dev/null 2>&1 || systemctl --user is-active --quiet budai.service; then
        systemctl --user disable --now budai.service
    fi
    rm -- "$bud_unit"
fi
if [[ -f "$bud_entry" && ! -L "$bud_entry" ]] && grep -q -F -- '# Generated by BudAI' "$bud_entry" && grep -q -F -- "$PWD/scripts/budai" "$bud_entry"; then
    rm -- "$bud_entry"
fi
printf 'BudAI data remains in %s\n' "${BUDAI_DATA_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/budai}"
