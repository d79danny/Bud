#!/usr/bin/env bash
set -Eeuo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."
python3 - "$PWD" <<'PY'
import os
import sys
from pathlib import Path

root = Path(sys.argv[1])
config = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
data = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local/share"))
outputs = {
    "budai.desktop": data / "applications" / "budai.desktop",
    "budai.service": config / "systemd/user/budai.service",
}
for name, path in outputs.items():
    root_string = str(root)
    if any(char in root_string for char in (chr(10), chr(13), '"', chr(92), '%', '$', '`')):
        raise ValueError("The checkout path contains characters that require manual launcher configuration")
    if path.is_symlink():
        raise FileExistsError(f"Refusing to replace a symbolic link at {path}")
    rendered = (root / "configuration" / f"{name}.in").read_text().replace("@BUD_DIRECTORY@", root_string)
    if path.exists() and "# Generated by BudAI" not in path.read_text():
        raise FileExistsError(f"Preserving existing launcher at {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# Generated by BudAI\n" + rendered)
    print(path)
PY
